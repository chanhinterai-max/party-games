function norm(list, level, type) {
  return list.map((x, i) => {
    const o = typeof x === 'string' ? { t: x } : x;
    const touch = o.t.includes('{where}');
    return {
      id: `${level}-${type}-${i + 1}`,
      level,
      type,
      text: o.t,
      touch,
      where: touch ? (o.where || WHERE) : null,
      group: true,
    };
  });
}

export const BANK = Object.fromEntries(
  LEVEL_IDS.map((lv) => [lv, { truth: norm(truths[lv], lv, 'truth'), dare: norm(dares[lv], lv, 'dare') }])
);

export function findWhat(id) {
  for (const lv of LEVEL_IDS) for (const ty of ['truth', 'dare']) {
    const w = BANK[lv][ty].find((x) => x.id === id);
    if (w) return w;
  }
  return null;
}

// Render a queue item into display text for the current player.
export function renderCard(item, whoText) {
  let t = item.what.text;
  if (!t.includes('{who}')) t = `Tell {who}: ${t}`;
  t = t.replaceAll('{who}', whoText);
  if (t.includes('{where}')) t = t.replaceAll('{where}', item.where || 'hand');
  return t.charAt(0).toUpperCase() + t.slice(1);
}
